def P(text, style):
    return Paragraph(text, style)


def make_table(headers, rows, col_widths, s):
    data = [[P(h, s["th"]) for h in headers]]
    for row in rows:
        data.append([P(str(c), s["cell"]) for c in row])
    t = Table(data, colWidths=col_widths, repeatRows=1)
    cmds = [
        ("BACKGROUND", (0, 0), (-1, 0), NAVY),
        ("VALIGN", (0, 0), (-1, -1), "TOP"),
        ("GRID", (0, 0), (-1, -1), 0.35, BORDER),
        ("LEFTPADDING", (0, 0), (-1, -1), 4),
        ("RIGHTPADDING", (0, 0), (-1, -1), 4),
        ("TOPPADDING", (0, 0), (-1, -1), 3),
        ("BOTTOMPADDING", (0, 0), (-1, -1), 3),
        ("BACKGROUND", (0, 1), (-1, -1), WHITE),
    ]
    for i in range(1, len(data)):
        if i % 2 == 0:
            cmds.append(("BACKGROUND", (0, i), (-1, i), ROW_ALT))
    t.setStyle(TableStyle(cmds))
    return t


def footer(canvas, doc):
    canvas.saveState()
    canvas.setStrokeColor(BORDER)
    canvas.setLineWidth(0.4)
    canvas.line(1.6 * cm, 1.35 * cm, A4[0] - 1.6 * cm, 1.35 * cm)
    canvas.setFont("DejaVu", 7)
    canvas.setFillColor(colors.HexColor("#7a8490"))
    canvas.drawCentredString(
        A4[0] / 2,
        0.85 * cm,
        f"Ritchson-стиль · сброс веса ≤2500 ккал · РФ-добавки  |  стр. {doc.page}  |  не медсовет",
    )
    canvas.restoreState()


